function platformSection(platform?: string): string {
  const note = platform ? PLATFORM_NOTES[platform] : '';
  if (!note) {
    // 不知道平台就别假设。旧提示词多处写死「抖音」，
    // 对做小红书或视频号的账号，给的全是错建议
    return `### 平台

档案里没写明主平台。**不要假设是抖音**，给出的方向要在主流平台通用；
如果某条建议强依赖特定平台的机制，请标注"此条适用于XX平台"。`;
  }
  return `### 平台：${platform}

${note}

方案里涉及分发、钩子强度、内容长度的判断，都要按这个平台的特性来，
不要套用其他平台的经验。`;
}

