export function buildPositioningPrompt(p: PositioningPromptParams): string {
  const focus = p.focus ?? 'full';
  const parts: string[] = [];

  const role =
    focus === 'business'
      ? '你是一位帮实体商家和个人IP做短视频变现设计的操盘手。'
      : focus === 'content'
        ? '你是一位帮账号排内容结构的短视频内容策划。'
        : '你是一位资深的短视频账号定位顾问，带过大量实体商家和个人IP起号。';

  parts.push(`${role}

**你不是在填表**。下面给了一整套判断依据，你要用它们做判断、给出有理有据的结论，
并且每一个结论都要说清"为什么是这个"。只把小节填满、说一堆正确的废话，等于没做。`);
  parts.push('');

  parts.push('## 📋 这个账号的情况');
  parts.push('');
  parts.push(p.profileSummary.trim());
  if (p.additionalNotes?.trim()) {
    parts.push('');
    parts.push('**用户补充说明**（优先级高于上面的档案）：');
    parts.push(p.additionalNotes.trim());
  }
  parts.push('');

  if (p.baseline?.trim()) {
    parts.push('## 🧱 已确定的定位地基');
    parts.push('');
    parts.push(p.baseline.trim());
    parts.push('');
    parts.push('⚠️ 以上是这个号已经定好的方向。你这次只做其中一维的深挖，**必须与它一致**，');
    parts.push('不要另起炉灶。如果你认为地基里有明显问题，先用一句话指出来，再按它往下做。');
    parts.push('');
  }

  parts.push('## 📚 判断依据');
  parts.push('');
  parts.push(AUDIENCE_CHANGE);
  parts.push('');

  if (focus === 'full') {
    parts.push(SIX_DIMENSIONS);
    parts.push('');
    parts.push(PERSONA_ENTRIES);
    parts.push('');
    parts.push(CONTENT_MIX);
    parts.push('');
    parts.push(COHERENCE_CHECK);
  } else if (focus === 'content') {
    parts.push(CONTENT_MIX);
    parts.push('');
    parts.push(COHERENCE_CHECK);
  } else {
    // 变现深挖：内容类型表仍然要给，因为变现型内容怎么排要靠它
    parts.push(CONTENT_MIX);
  }
  parts.push('');

  parts.push(platformSection(p.platform));
  parts.push('');
  parts.push(restrictionSection(p.restrictions));
  parts.push('');

  parts.push(focus === 'business' ? OUTPUT_BUSINESS : focus === 'content' ? OUTPUT_CONTENT : OUTPUT_FULL);
  parts.push('');

  parts.push(`## ✍️ 写作要求

- **有依据**：每个结论后面都要能说出为什么。说不出理由的结论直接删掉
- **可落地**：所有建议必须在这个账号的真实资源（设备、团队、场地、时间）之内
- **具体**：不要写"打造专业形象""提升用户粘性"这类任何账号都能套的话
- **敢说不**：档案里有明显不适合的地方（比如资源撑不起想做的形式），直接指出来
- 篇幅按需要来，不要为了凑字数灌水，也不要为了简短牺牲判断过程`);

  return parts.join('\n');
}
