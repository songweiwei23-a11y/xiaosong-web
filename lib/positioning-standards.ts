/**
 * 账号定位的方法论。
 *
 * 【原来为什么不满意】旧提示词写在 /api/dify/stream 路由里，四百多行
 * parts.push，内容全是「输出这些小节、每节写几条」——规定的是**格式**，
 * 没给**判断依据**。模型于是把小节填满，但说不出为什么是这个人设、
 * 为什么这个配比、凭什么这条路能变现。这和分镜改造前是同一个病：
 * 产出格式正确，但不是专业方案。
 *
 * 另外三个具体毛病：
 *   · 和我们自己的知识库脱节。「IP定位表六维地基」在 Dify 里能原文检索到，
 *     旧提示词一次都没要过它，自己另起了一套小节。
 *   · 多处写死「抖音」，而档案支持快手、小红书、视频号、B站。
 *   · 限制 1000 字并明确要求「不要输出变现路径」——定位是地基，
 *     砍掉变现这一维，等于把最要紧的一块挖掉了。
 *
 * 【这里补的是什么】知识库里编导真正在用的判断依据：
 *   1. 底层逻辑——内容要让观众发生哪种变化，这是判断方向成不成立的标尺
 *   2. 六维地基——人设/用户/内容/呈现/风格/变现，每维有关键问题和验证标准
 *   3. 人设七入口——每个入口都配一个验证问题，专治「人设写得漂亮但立不住」
 *   4. 内容五类型——各自要证明什么、常见风险，以及基准配比与新号策略
 *   5. 自洽检验——遮住字幕/只听声音/三件套是否像同一个号
 *
 * 【一个函数三种用法】focus 决定做全套还是深挖某一维：
 *   full     六维地基（账号定位板块）
 *   business 变现定位深挖（商业定位板块）
 *   content  内容定位深挖（内容定位板块）
 * 深挖时把已有的地基原文传进来，避免用户重复填一遍，也避免两份产出打架。
 */

export type PositioningFocus = 'full' | 'business' | 'content';

export interface PositioningPromptParams {
  /** 账号档案摘要，由调用方按档案字段拼好 */
  profileSummary: string;
  /** 用户的补充说明 */
  additionalNotes?: string;
  /** 主平台，决定平台差异那一段；取不到时不写死任何平台 */
  platform?: string;
  /** 档案里的「绝对不能说」，硬约束 */
  restrictions?: string;
  focus?: PositioningFocus;
  /** 深挖模式下已有的六维地基原文 */
  baseline?: string;
}

