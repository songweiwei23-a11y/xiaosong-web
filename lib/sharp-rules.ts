/** 标题：具体的东西 + 一个反差、冲突或悬念；禁用万能模板 */
export const TITLE_CRAFT = `标题要有**具体的东西**（一件事、一个处境、一个数字或一个人，不一定是商品细节）加一个**反差、冲突或悬念**，观众刷到第一眼就知道这条说的是什么、为什么跟他有关。不用「XX，怎么…」「别只…」「你知道吗」「XX 的 N 个技巧」「原来…」这类万能模板。标题不超过 20 个字，只有一个主句，不用分号把几句话连成一串。标题里不留占位符（X、某某、几元、XX 这类）：要么写出真的数字和东西，要么换一个不需要填空的说法。标题要读起来像一句人话，不硬拼两个不相干的名词或比喻（「压箱底的裤子，像怕被评价的人」这种就不通）。写完先把标题通读一遍，读不顺、看不出在说什么的就重写。写法对照（只学写法，不照抄）：平：「装修选材料，别被忽悠」（只有话题，没有东西，也没有冲突）；好：「同一面墙，两种漆，三年后差在哪」（具体的东西、一个对比、一个悬念）`;

/** 开篇第一句：一个具体的画面、动作或有冲突的话，第一秒就能看见 */
export const OPENING_CRAFT = `第一句要是一个具体的画面、动作或一句有冲突的话，观众第一秒就看得见。不写「今天我们来聊聊」「大家好」「很多人不知道」这类引出话。写法对照（只学写法，不照抄）：平：「今天跟大家说说怎么选裤子」；好：「站着看合身，坐下勒不勒？我让店员当场坐下给你看」`;

/** 人和事只写真的：人设、经历、顾客原话都要有出处 */
export const REAL_PEOPLE_RULE = `人和事只写真的：人设里要让人记住的那个人、那件事，只用档案写的或前采里说的；不让店员或别人扮演顾客，不替老板编性格、经历、顾客原话。没有的，写「待确认：缺哪一条」，并给出先要问的那个具体事件。`;

/**
 * 逻辑遵循现实（2026-10-26 产品方定）：一件小事只能改变它直接作用的那一处，结论不能比证据大。
 * 注意：这条只管「说法离不离谱」，不管「对比该变哪一样」——对比要变的是卖的东西，见下面的 PRODUCT_HERO_RULE。
 */
export const REALITY_RULE = `任何创作都必须符合现实的生活逻辑，有说服力才行。创作的来源只能是现实中真实存在、大多数人认可的事，不凭空编造。下面三类说法一律不写（括号里的例子只说明是什么类型，不是清单，类似的说法同样不写）：
- 太离谱：一件事改变整体、判若两人、几天就见效的保证（比如「收腰就能换风格」「换个头像粉丝就翻倍」「同一件外套两种人」「换个招牌字体，营业额就翻一番」）
- 太简单：一招搞定、一句话让客户当场签单、躺着就能赚（比如「一句话让客户当场下单」「躺着月入过万」）
- 太不科学：违背常识或没有依据的因果（比如「喝某种水就能瘦」「敷一下就能消炎」）
一件事能带来的变化，要有它真实的条件、过程和代价。反差和看点要来自生活或镜头里看得见的具体变量，不靠硬切换人设、身份或结果。拿不准能不能成立，就写清楚前提和做法，不替事实下结论。一个小细节（一种做法、一个动作、一句话、一处调整）只能改变它直接作用的那一处，不能写成它让整件东西、整个人或整家店都变了。结论的范围也要和证据一样大：一次现场的反应只说明这一次，不能推成普遍的道理（比如一位客户换了靠垫说舒服，就说挑沙发都要试靠垫）。`;

/**
 * 主角是卖的东西（2026-10-29 产品方定）：对比、反差、前后变化证明的必须是这个号卖的东西好。
 * 线上内容规划出了「同一件衣服两种穿法」：衣服没变、变的是穿法，前后差别只能归功于技巧，证明不了衣服好，
 * 观众学会穿法也就不用来买。做账号的逻辑是同一个人换两套衣服、前后两种风格——人和场不变，变的是货。
 * 知识库原话：变现型要「展示你为客户做的事」；效果对比是「同样的食材，我们的做法和普通做法的差别」；
 * 验证钩子是「剪发前后对比验证手艺价值」。卖手艺、卖服务的，手艺本身就是货。
 */
export const PRODUCT_HERO_RULE = `主角是这个号卖的东西：观众看完要觉得「是这家的东西（或手艺）让人变好看、变好用、变好吃」，而不是学会一个技巧就不用来买了。
- 要做对比、反差、前后变化，变的那一样必须是这个号在卖的东西，其他条件不变：同一个人（同一个空间、同一桌人）先后用两样东西——这家卖的，和普通的、旧的或常见的——前后差别看得见，才证明是东西好。例：同一个人先后穿两套衣服，前后两种风格；同一个客厅换两张沙发；同一个人戴两副镜框
- 不做「同一件东西换个穿法、搭法、摆法、用法、吃法」的对比：卖的东西没变，差别只能归功于技巧，证明不了东西好，也给不出来买的理由
- 卖的就是手艺或服务的（剪发、验光、装修设计、厨师的做法），手艺本身就是货：同一个人剪前剪后、同一份食材我们的做法和普通做法，这类对比成立
- 穿法、搭法、用法这类技巧只能顺带一句，不能当一个方向或一条内容的看点；人设型的主角是人，不受这条限制`;

