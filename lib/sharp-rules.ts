export const BIG_OPENING_RULE = `开口要大，但不离开定位：每条选题同时落在三处。赛道：账号在做的品类，观众一眼认出这是这个号的内容；赛道里的身份（大码、宝妈、学生这类身体或处境）要让观众一眼认出是他们的事，每条的内容方向里都要点出这个身份，不能只写「好物」「生活」这种笼统的词；标题里也要有一个赛道词（比如衣服、穿、裤、外套，或沙发、菜、锅、店这类，按这个号的行业来），不能只剩情绪或大众话题。目标人群：分配表里这一条的人群，写他们的处境；标题里不照抄分配表的标签，不写「25—30岁宝妈」「18—24岁学生」这种年龄加身份，人群写进处境和事情里。大众大事：大多数人都会遇到的事（钱、时间、面子、舒服、家人、买错、被误解），让圈外的人也想点开。切口可以大，话题不能脱离赛道和人群。只讲商品的操作细节不行；门店流程（进店、看价签、结账）只是背景。爆款元素是标题和第一秒的看点：流量选题的标题要光看就认得出分给它的那个元素（用它的句式写），元素要落在赛道、人群、大众大事这三处上，不能脱离它们单独成立。`;

