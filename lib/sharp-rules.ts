/** 标题：具体的东西 + 一个反差、冲突或悬念；禁用万能模板 */
export const TITLE_CRAFT = `标题要有**具体的东西**（人、物、数字、地点）加一个**反差、冲突或悬念**，观众刷到第一眼就知道这条说的是什么、为什么跟他有关。不用「XX，怎么…」「别只…」「你知道吗」「XX 的 N 个技巧」「原来…」这类万能模板。标题不超过 20 个字，只有一个主句，不用分号把几句话连成一串。写法对照（只学写法，不照抄）：平：「装修选材料，别被忽悠」（只有话题，没有东西，也没有冲突）；好：「同一面墙，两种漆，三年后差在哪」（具体的东西、一个对比、一个悬念）`;

/** 开篇第一句：一个具体的画面、动作或有冲突的话，第一秒就能看见 */
export const OPENING_CRAFT = `第一句要是一个具体的画面、动作或一句有冲突的话，观众第一秒就看得见。不写「今天我们来聊聊」「大家好」「很多人不知道」这类引出话。写法对照（只学写法，不照抄）：平：「今天跟大家说说怎么选裤子」；好：「站着看合身，坐下勒不勒？我让店员当场坐下给你看」`;

/** 人和事只写真的：人设、经历、顾客原话都要有出处 */
export const REAL_PEOPLE_RULE = `人和事只写真的：人设里要让人记住的那个人、那件事，只用档案写的或前采里说的；不让店员或别人扮演顾客，不替老板编性格、经历、顾客原话。没有的，写「待确认：缺哪一条」，并给出先要问的那个具体事件。`;

/** 每条只押一个最强的看点：一句话说死，不列两三个方案让人自己挑 */
export const ONE_POINT_RULE = `每条只押一个最强的看点，用一句话说死它为什么会让人停下；不写「可以/也许/建议」这类两可的话，不把两三个方案摊开让编导自己挑。`;
