import { routeAssignment, type CreativeRoute } from './creative-routes';

/** Automatic continuation should not offer unrelated shooting formulas. */
export function topicPreferredTactic(p: { source: string; direction?: string; explicit: boolean }): string | undefined {
  if (p.explicit || !p.source.trim()) return undefined;
  const material = [p.direction, p.source].filter(Boolean).join('\n');
  if (/不(?:要)?(?:做)?(?:采访|街采|街访)/.test(material)) return undefined;
  return /采访|访谈|街访|问.{0,8}(?:老板|店主|商家)|(?:老板|店主).{0,8}(?:真实感受|真实反应)/.test(material) ? '街头采访' : undefined;
}

/** A direction is a brief to execute, not a record of already filmed episodes. */
export function topicSourceRules(hasScript: boolean): string {
  return (hasScript ? [
    '- 从当前稿件的具体人物、事件、细节或观点提炼更有价值的切口；同一件事可以深化问题、补证据、换观察维度，不另编一段人生经历。',
    '- 原稿里的采访、前后对比、过程记录等核心取材方式继续保留，不能只保留话题词就换成另一种节目。',
    '- 不把当前稿里的AI示范情节当作已发生事实；已有真实素材能支撑什么才写什么。',
  ] : [
    '- 方向中的选题示例、提问和拍法是待落实的创作线索，不是已经拍完或必须避开的内容。用户想落实它，就优先把最贴合目的的一期做深。',
    '- 可以沿用方向里的好问题、采访对象和对比维度，但必须增加具体提问、内容推进和取材方法，不能只是改标题；只有用户明确要求另出全新选题时才避开原示例。',
    '- 保留核心行动：用户要问老板真实感受，就策划如何问、怎样追问、如何比较真实回答；不能换成偷拍电话、全天跟拍或无关情感故事。',
    '- 原文里的X、XX、示例和待确认数字不是事实，不能补成具体金额、人数或亲历故事。',
  ]).join('\n');
}

export function topicRoutePrompt(p: { route: CreativeRoute; count: number; sourced: boolean; explicit: boolean }): string {
  if (!p.sourced || p.explicit) return routeAssignment(p.route, p.count);
  return [
    '【本批拍法按已选方向自动决定】',
    '用户从已有方向或稿件继续创作，页面默认「两种都出」不是用户要求改拍法。',
    '优先保持原来的采访、观察、对比或过程拍法，在四大脚本与36计中选择真正服务它的结构；两套可以互补，但不为了各占一半而拆散同一核心行动。',
    p.count + '条可以使用同一最佳拍法，区别应落在核心问题、证据、人物关系或对比维度上；不能强凑剧情、跟拍或套路。用户手动指定拍法时遵从指定。',
  ].join('\n');
}

/** Give the director an executable editorial question, not a decorated title. */
export function topicDesignStandards(p: { source: string; direction?: string; userIntent?: string }): string {
  const material = [p.direction, p.userIntent, p.source].filter(Boolean).join('\n');
  const interview = /采访|访谈|问.{0,8}(?:老板|店主|商家)|(?:老板|店主).{0,8}(?:真实感受|真实反应)|你问一句.{0,8}答一句/.test(material);
  const comparison = /前后|前.{0,12}后|期间.{0,15}节后|国庆.{0,15}(?:过后|后)|对比|比较/.test(material);
  const lines = [
    '【选题质量：先设计要拍到的内容，再写标题】',
    '一条成熟选题至少说清：具体主体、值得验证的核心问题、为什么目标观众在意、到现场怎样获得内容、真实材料怎样推进这条片子。标题、情绪词和「反差/共鸣/扎心」不能替代这些。',
    '- 先锁定本轮的核心行动和观察对象，把它写成一个能被素材回答的问题。每条都服务用户目的，不能只是主题词相同。',
    '- 深度来自有价值的问题、对照和追问，不来自猎奇、煽情或强套爆款句式；每条要让观众多理解一个具体问题。',
    '- 区分拟拍方案与已完成报道。未知结果写成问题或待验证方向；没有素材不要写「我发现一半店关了」「他的话让我眼眶红了」等预设发现。',
    '- 统计比例、技术尺寸、价格、节省金额和普遍经营规律必须有当前材料依据。没有依据就用问题、演示或待测量项，不造「90%的人」「补货频次就是生意硬指标」来撑权威。',
    '- 内容推进要落到具体问题、动作、证据和剪辑关系，不用「制造共鸣→引发讨论」当故事骨架；不能为了十字限制省掉关键步骤。',
    '- 首条优先把用户明确要拍的那一期做扎实，不能因它不够新奇而只给旁支。其余选题保持同一核心对象和拍法，分别深入不同问题；不得为求新奇牺牲原目的。',
    '- 保留八大爆款元素、四大脚本与36计的编导方法，但方法服务真实问题，不让模板替用户决定要拍什么。',
  ];
  if (/测量|尺寸|开合空间/.test(material)) lines.push(
    '本轮若用实物测量教学：手机用于拍照、记录，真实尺寸由合适工具测量；不把手机大小当柜门尺寸、不冒充可靠测距工具。用当前样品实测的开合范围演示，再核对现场障碍与通道，不编统一预留厘米数或技术标准，不用假返工价制造焦虑。',
  );
  if (interview) lines.push(
    '\n【真实采访型选题的取材要求】',
    '每条给一组能实际问出口的主问题和2～3个追问，写明访问哪些对象、如何选择，不替受访者预写答案。',
    '本轮核心行动是采访，每条都保留向受访者提问并采集真实回答的主体。四大脚本可辅助组织回答，不能改成主播讲知识、泛行业观点或用关门时间猜经营趋势。',
    '不要止于「生意怎么样/什么感受」，也不要诱导悲惨或成功结论：追问具体发生了什么、与什么比较、为什么、能否给一个不涉及隐私的例子。',
    '不同店主可能变好、变差或没变化；说明如何保留不同回答、寻找原因，不能先宣布「老板都很惨」「分三种人」再找素材证明。',
    '拍摄征得同意，不安排偷拍、偷录或打断经营。无需靠全天跟拍兑现一个本可通过短访谈回答的问题。',
    ...(comparison ? [
      '对比必须有共同口径：同一店的前后时段、客流/经营感受/忙碌程度等具体维度；同街不同业态的回答不要直接混成总趋势。没账本可用具体经历和现场观察，不能把感受包装成营收统计。',
      '每条主问题直接比较用户指定的前后变化，不能把核心问题降成「你几点关门」「忙是什么意思」「你期待哪个节点」。这些只可作为回答之后的补充追问。',
      '本批每条都共用一个必问主问题：用户指定的前后时段，店里生意究竟变没变、具体变在哪里？再各自深入一个与变化有关的问题。输出时明确列「主问题（原目的）」与「本条深入的问题」，不能用深入的问题替换主问题。',
      '用户要前后生意对比，不要把整批安排成客观变化→焦虑→未来预期的五段扩题。每条独立成立且都保留前后对比，切口可围绕客流与消费差异、客群变化、忙碌时段、变化的原因或据此做出的经营调整。没有用户要求，不另出未来预测或泛情绪采访。',
      '好的内容推进：先问同一店指定前后时段生意的变化→追问客人数量、消费方式或忙碌时段中究竟哪一项变了→请老板讲一个具体例子→再问他判断原因的依据。遇到没变化或不知道原因也保留，不强求反转。',
    ] : []),
    '剪辑结构要写清主问题→不同真实回答→关键追问/现场证据→有边界的观察，采访问题与回答骨架带去写脚本继续使用。',
    '没有采访结果时交付采访执行方案和不预设答案的开头，不写假采访实录。',
    '还没采访时，标题和开头用准备验证的问题：要去问什么、为什么值得问。不用「我问过/我发现/居然/原来/有人已经」的报道语气，不填采访家数、答复比例或具体台词；计划访问几家也不能写成已经问完。',
    '同批每个切口都必须回应用户要比较的那件事。前后生意对比就逐店询问前后变化和具体依据，不能仅靠国庆背景改成营业时间观察、泛泛情绪或与生意变化无关的人生话题。',
    '输出采访问题和待采集画面，受访者回答的位置写「保留现场原话」，不要写老板A/B/C的示范答案。剪辑分支写条件：如果答案不同怎样对照，如果一致怎样追问依据，不假定一定有反差。',
    ...(comparison ? [
      '参考表达方式（示例用于理解，不替用户换主题）：题目「假期前后，店里的生意究竟变在哪？」；开头「假期结束，店里生意到底变没变？今天去问问这条街的老板。」；主问题「跟假期那几天比，现在店里生意有什么变化？」；追问「具体是人少了、买得少了，还是忙的时段变了？也可能没变，您实际是哪种？」「能讲最近一个让您这样判断的具体情况吗？」「您觉得和假期结束有关，还是另有原因？怎么判断的？」。这是事前采访设计，不能改成「我问了一圈发现…」或为老板填答案。',
    ] : []),
  );
  return lines.join('\n');
}

/** Keep the execution criteria near the point where the model begins its answer. */
export function topicDesignFinalCheck(): string {
  return [
    '【交付前最后核对：选题必须能直接指导真实创作】',
    '- 逐条检查：问的仍是不是用户最初那个核心问题？只是背景相同、换成另一种节目，不算承接。',
    '- 没有用户提供的采访实录时，标题和开头只写待验证问题、准备去做的行动，不写任何已采访结果、人数比例、经营发现或受访者台词。标题有吸引力也必须能被现有素材兑现。',
    '- 不先挑一批「忙/闲/早关门/停止补货」的老板凑预设反差；先选对象并问相同核心问题，再由真实回答决定剪辑。写出不同或一致答案时如何成立。',
    '- 深化方向里的好问题是允许的。新增价值来自问题、追问、证据或观点关系，不能因为过去生成过采访题就绕去偷拍、煽情或猎奇。',
    '- 写清具体问题和取材步骤，合并重复的价值/目的说明，不反复讲共鸣、站队、痛点等标签。不要另写「自检通过」「没有编造」作为质量证明。',
  ].join('\n');
}

