/**
 * 内容规划、创作方向共用的「好方向标准」（2026-10-29 瘦身）。
 *
 * 为什么收成一份：10-29 一天里为了修「方向像观点」「部位清单」「预算先买哪件」「证明试穿有用」「门店流程」
 * 「换季衣柜」，在这两个板块上叠了出发点方法、九类切口、八大元素说明、主题三问、方向形状、36 计全量公式，
 * 规则部分超过整份提示词的一半（规划约 10800 字），而且大多是「不许做 X」。模型每次都换到下一个不犯规的
 * 保守写法上，配额（人货场各几个、有用不过半）又把好题挤掉，去凑数。
 *
 * 现在的写法：正面标准在前（出发点定义、好方向长什么样、主题从哪来、元素让观众看到什么），
 * 少量红线，搭配要求放到最后当「交稿前对照」，先保证每个方向够好再看整批搭配。
 * 第十二轮真实核验：对照项模型执行得松——大码号 7 个流量方向 5 个讲换季（系列名就叫换季烦恼），反差还是变动作、变情绪。
 * 所以「同一话题最多 2 个（系列大主题也算）」「反差两边必须是两样货、两类人或两个时代」挪进红线。核心逻辑一条没删：
 * 产品方的出发点定义、三有之一、人货场之一、任何脚本结构 + 爆款元素都是大流量、流量不带成交理由、
 * 反差变货、品类不同框、选择题最多 3 个、系列只作参考、借 36 计、人群身份。
 */
import { VIRAL_ELEMENTS } from './viral-elements';
import { BIG_TRAFFIC_STANDARD, TRAFFIC_DIRECTION_TYPES, sellingPointsOf } from './content-roles';
import { GROWTH_TACTICS } from './growth-tactics';
import { tacticsBlockedBy } from './creative-routes';

/** 每个元素让观众看到什么（元素是看点的来源，不是标签），句式取知识库原文第一条 */
const ELEMENT_SEES: Record<string, string> = {
  成本: '一笔意外的账：花小钱办成了什么、省下多少时间或力气（不是在内容里提到预算）',
  人群: '这群人才有的处境被拍出来（不是开场点个名）',
  反差: '两样货、两类人、两个时代摆在一起，差别看得见；同一件东西换视角、换动作、挂着和穿上，处境上的落差，都不算',
  最差: '大家踩过的坑（市面上的旧款、别处的坑，不骂自己卖的货）',
  怀旧: '那个年代的东西真的出现在画面里',
  奇葩: '外行不知道的那一层门道（不是人的小动作或犹豫）',
  头牌: '真有的那个「最」（平价店不硬写最贵）',
  荷尔蒙: '异性或旁人眼里的评价（不是「想让自己状态好一点」）',
};

/** 八大元素，一个一行：让观众看到什么｜句式 */
export function elementSeesBlock(): string {
  return VIRAL_ELEMENTS.map((e) => {
    const where = e.only ? `（只适合${e.only.join('、')}）` : e.avoid ? `（不适合${e.avoid.join('、')}）` : '';
    return `- **${e.name}**${where}：${ELEMENT_SEES[e.name] ?? e.hook}｜句式如「${e.patterns[0]}」`;
  }).join('\n');
}

/** 36 计只列计名（找主题用；公式在内容定位和选题层），和账号禁忌冲突的拿掉 */
export function tacticNamesLine(contextBlock = ''): string {
  const blocked = new Set(tacticsBlockedBy(contextBlock));
  return GROWTH_TACTICS.filter((t) => !blocked.has(t.name)).map((t) => `第${t.no}计 ${t.name}`).join('、');
}

export function directionStandard(p: { profileSummary?: string; contextBlock?: string } = {}): string {
  const points = sellingPointsOf(p.profileSummary);
  const pointsLine = points.length ? `（这个号的成交理由是${points.map((x) => `「${x}」`).join('')}，留给变现型）` : '';
  return `## ✅ 好方向的标准（先照它挑，最后对照检查）

### 一、出发点（产品方定义）
${BIG_TRAFFIC_STANDARD}
- **流量型 = 爆款元素 + 这群人感兴趣的话题**：最好的话题是这群人的身份处境（做大码女装的号：大码女生买衣服、被人评价身材、找不到尺码的经历），换一个不服务这群人的号就拍不了。不必挂在系列上，也不必是这家店独有的事。不推卖点、不讲价格，看点不能是在证明成交理由${pointsLine}
- **变现型 = 一个成交理由 + 卖的那样东西**：观众看完凭什么觉得它好（同一个人换上它的变化、它和普通的对比），落在画面、过程或结果里
- **人设型 = 让人记住这个人的一点**（性格、人品、一个举动），靠档案或前采里的一件真事撑着

### 二、好方向长什么样
一个方向是一类看得见、能反复拍的内容，能出至少 5 期不同的选题；不是一个观点、一个问题，也不是一个部位、一个动作。方向名不用「顾虑」「困惑」「态度」「取舍」「两难」「观察」「需求」「介绍」「日常」这类词收尾。写得出四样才算：**拍什么**（镜头里的货、人、事或场景）、**看点**（陌生人凭什么停下）、**观众看完得到什么**（有用＝带走一条信息，有趣＝哪里意外，有共鸣＝哪个瞬间像自己）、**这个号凭什么拍得出**。
- 好：「十年前的爆款外套今天穿」「店主不进货的那几种裤子」「大码女生最怕被问的那句话」
- 不好：「宝妈出门穿衣的顾虑」（议题）、「一套预算先买哪件」（选择题）、「抬手时外套肩背怎么动」（一个动作，只够一期）
- 例子只示范写法，换成这个号自己的人、货、事

### 三、主题从哪来
- 内容定位里的系列和前 10 集，好的**优先接过来**；有更好的可以换，系列只是参考。系列的大主题（比如「换季」）也是一个话题，照样最多接 2 个
- 借起号 36 计：挑这个行业、这群人、这些货套得进去的那一计，套成一类内容（计名见末尾；方向里不写定用哪一计拍，拍法留给选题层）
- 人设型、系列整体：先从这个号独有的事实里找（开店经过、经营方式、门店真实发生的事、店主的判断）
- 常见切口也可以参考：${TRAFFIC_DIRECTION_TYPES.map((t) => `**${t.name}**`).join('、')}
- 过两问：答案是不是人人都知道？陌生人刷到凭什么停下？过不了就换

### 四、八大爆款元素：让观众看到什么
${elementSeesBlock()}

### 五、红线（碰了就换）
- 不编人、事、数字和别人的反应；凭档案里的真实经验给判断、讲做法可以
- 流量型不推卖点、不讲价格，不证明成交理由
- 选反差：两边必须是两样货、两类人或两个时代；同一件东西换视角、换动作、挂着和穿上，想象和实际、情绪前后的落差，都不算，换别的元素。做反差或对比时，变的是卖的东西，人、场、动作不变
- 几个品类在一批里轮流出现，单条不用同框，不做「X、Y、Z 先买哪个」
- 只抛一道题让观众选的方向（换个道具问同一道题也算），一批最多 3 个；同一个话题（系列的大主题也算，比如换季）在流量方向里最多 2 个
- 档案和用户说过的禁忌，一条不碰

### 六、交稿前对照（先保证每个方向够好，再看整批搭配；明显不满足时，换掉最弱的那个，不为凑数加弱题）
- 流量方向里人、货、场都有（6 个以上时各至少 2 个）；三有至少用到两种，「有用」不超过一半
- 同一种看点、同一个元素，各最多 2 个；同一件货最多 3 个
- 至少一半流量方向带这群人的身份
- 流量方向不和变现方向用同一种拍法（比如两边都是「同一人换两条裤子」）

起号 36 计（计名）：${tacticNamesLine(p.contextBlock)}`;
}
