/**
 * 采访类内容的「交稿前最后一查」，由服务端拼在整条提示词最末尾（2026-10-08）。
 *
 * Dify 发布后复测（8 个板块）：上面【采访落地】里明明写了禁止「我问了一圈 / 每家答案不一样」，
 * 标题、方向和重新生成仍出现未采集的事实。末尾约束用于提醒当前材料状态，效果需正式复测。
 * 只在提示词里有【采访落地】时启用；真实采访摘要也可以是材料，不要求逐字实录。
 */
export function interviewFinalCheck(query: string): string {
  if (!query.includes('【采访落地】')) return '';
  return `\n\n【交稿前最后一查：采访有没有真做过】
以用户原始材料判断采访状态。真实采访摘要、记录或原话均可据实使用，旧 AI 草稿中的经历和结果不作事实来源。
明确尚未采访或没有结果时，所有候选都必须现在可用：只写准备问的问题和计划动作，不用完成时态，不写已观察的客流、恢复、答案差异、老板反应。加“采访后可用”也不能保留这些候选。不要输出错误示范来占用交付。
所有方向保持用户选定的采访对象范围与主问题，不擅自缩小或更换范围，也不延后原计划。比较任务保持同一比较口径；日期未给就留拍前统一，不代选日期。既有开头逐字保留；修改开头任务按用户本轮要求执行。
追问须允许变好、变差、没变、不确定。纯文案只放可念的主持人台词和问题；现场回答占位、动作与机位只放执行稿或分镜。`;
}

/** 两个生成接口在全部材料组装完后使用；不影响未标记请求或高阶自由对话。 */
export function creativeFinalCheck(query: string): string {
  if (!query.includes('【本轮内容落实规则】') || query.includes('【高阶自由对话】')) return '';
  return interviewFinalCheck(query) + `\n\n【交付前落实当前内容】
只完成本轮要求的板块。候选逐条服从原意、已选主线、资源和事实状态；删除不成立的候选后补同主线可用版本。
演示只用实际样品可验证的操作，不假定结构、统一开门角度、尺寸标准或免费服务；需精确尺寸时说明用适合的测量工具复核，估算不能替代测量。新增支架、工具、人员标可选并给现有资源替代。
分镜的已知台词按约5字/秒作为排时估算，再加动作、停顿；完整问题不得压缩进念不完的秒数。未知回答的时长仅为暂估，现场按完整回答调整；总秒数必须按表逐行真实相加，统计也必须对应表格。
只交付可用内容和必要待确认项；不复述规则、不自称通过、不追加反例、不编平台最佳时长或指标合格线。`;
}

/** Content-level checks shared by the continuation steps, beyond carrying topic labels. */
export function creativeCraftRules(p: { intent?: string; selected?: string; source?: string; context?: string }): string {
  // The root brief is authoritative. A draft may already contain the mistake we are fixing.
  const root = p.intent?.trim() || p.context?.match(/^- 原始用户想法：([^\n]+)/m)?.[1]?.trim();
  const material = [root || p.source, p.selected].filter(Boolean).join('\n');
  const interview = !/不(?:要)?(?:做)?(?:采访|街采|街访)/.test(material)
    && /采访|访谈|街访|问.{0,8}(?:老板|店主|商家)|(?:老板|店主).{0,8}(?:真实感受|真实反应)/.test(material);
  const comparison = /前后|前.{0,12}后|对比|比较/.test(material);
  const rules = [
    '【本轮内容落实规则】',
    '- 原始用户想法及本轮明确修改决定目的、主体、比较对象、时间范围和取材方式。已有 AI 稿只作待核对草稿，不能把其中示范情节、假定回答或推断当作新增真实素材。',
    '- 先完成当前这条内容；深化来自具体问题、证据、动作及信息关系，不能因追求流量先换节目、等涨粉后再兑现本来的任务。方法库用于解决问题，不用于补造冲突、结果或情绪。',
    '- 只使用已确认资源。建议的人员、设备、场地或服务须写为可选且说明替代；不凭空承诺免费服务、价格、优惠、效果，不设未经验证的完播率或成交率合格线。效果看用户自己的基线和真实数据。',
  ];
  if (interview) rules.push(
    '【采访落地】每个切口先写同一个必问主问题，再写该切口深入的问题及至少两条条件追问。不要只问“生意怎么样”：追问具体变化、可分享的事例、判断依据。不要把关门时间、泛情绪、未来预期换成主问题。',
    '- 不预设答案不同、有反转或老板沉默：如果不同，比较各自依据；如果一致，深入共同原因与例子；不知道也如实保留。店主的感受不能包装成营收统计或整座县城趋势。',
    '- 无采访实录或用户明确尚未采访时，全部候选标题、开头、正文、封面及建议都按事前方案写，只说准备问什么或待验证的问题。禁止“我问了一圈/问过几家/每家答案不一样/他的话让我意外”等已完成报道语气，禁止预填老板台词、答复比例、经营结果。参考稿出现这些句子也必须改正。已有真实实录时才可据实保留。',
    '- 纯文字文案只放已知主持人/旁白台词和实际提问，不放未知回答占位，也不写未经采访验证的总结；受访者的“按现场真实回答”只放采访执行稿或分镜中。',
  );
  if (comparison) rules.push(
    '【比较口径锁定】先从原始用户想法确定两端是什么，在所有主问、追问、标题、正文与分镜里保持同一口径。前后对比不能偷偷变成同比、和往年比、与平时比；用户明确要这些比较时才使用。',
    '- 原意只说“前后”未给日期时，具体日期和口径待核对，不擅自改换比较对象。各对象保持相同时间范围和维度，不能拿不同长度的总量直接比较。',
  );
  if (comparison && interview) rules.push(
    '- 若用户只说国庆前后，主问题示范：“跟国庆前的那段时间比，国庆后这几天您店里生意有什么变化？”具体日期拍前统一。追问示范：“具体是来客、每单消费、忙的时段哪一项变了？也可能没变，您实际是哪种？”“能说一件让您这样判断的具体事吗？”“您觉得原因是什么，有什么依据？”示范仅适用于这个原意；用户明确假期期间与节后，则按那两个时段问，不能套节前。',
    '- 没有前期录像也可采访同一店主对两个时段的回忆，再记录当下可见现象并注明证据边界；不安排回到已过去的日期补拍，不编两次走访，不要求全天跟拍来替代短访谈。',
  );
  return rules.join('\n');
}
