/**
 * 大流量视频不带成交理由（2026-10-25 产品方定）。成交理由只属于变现型内容，
 * 任何要把成交理由写进内容的地方，先过这一道：流量型返回空，其余原样返回。
 */
export function dealReasonsForPurpose<T>(purpose: string | null | undefined, reasons: T[]): T[] {
  return purpose === '流量型' ? [] : reasons;
}

