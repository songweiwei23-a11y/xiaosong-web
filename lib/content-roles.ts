export interface RoleSpec {
  /** 这条视频替账号干什么活（SOP 原话） */
  job: string;
  /** 拍什么方向（小黄 9.1 三种目的 + 十大方向） */
  directions: string;
  /** 形式：可以用什么脚本或拍法（形式不决定目的） */
  scriptTypes: string;
  /** 结构的例子，骨架要写到能直接套；任何目的都可以从这里或别处选 */
  structures: string[];
  /** 怎么策划 */
  planning: string;
  /** 看什么数据算成了（小黄 9.1 成功指标） */
  metrics: string;
  /** 结尾行动指令——只选一个（SOP：三个都要 = 三个都失败） */
  cta: string;
  /** 最常见的错 */
  pitfalls: string;
  /** 标题和开头怎么抓人（给标题、开篇板块） */
  hook: string;
  /** 镜头重点（给分镜板块） */
  shots: string;
}

