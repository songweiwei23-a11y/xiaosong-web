/**
 * 三种视频：流量型（大流量）/ 人设型 / 变现型——全站唯一出处。
 *
 * 【2026-10-25 产品方定：大流量视频怎么定义】
 * 大流量视频由内容本身定义，不由脚本定义：
 *   1. 围绕「人、货、场」设计（谁在拍、拍什么或卖什么、在哪拍）
 *   2. 符合三有原则：有用、有趣、有共鸣，至少符合其中一条（不要求全部）
 *   3. 用上八大爆款元素（名单见 lib/viral-elements）
 *   4. 有看点、有噱头，能吸引眼球
 *   5. 不带成交理由：不讲卖点、不推产品、不引导私信或到店；产品只作为画面里的货出现（2026-10-25 产品方定）
 * 36 计、四大脚本、反常识开篇等都只是把内容拍出来的形式，任何一种都能用在大流量视频上，
 * 也都能用在人设型、变现型上。脚本不决定目的，目的由这条内容要达到的效果决定。
 *
 * 【为什么要收成一份】原来每个板块各说各的：
 *   - 脚本板块写"教知识→涨粉、聊观点→吸真粉丝、晒过程→促变现、讲故事→成交高客单"（薛老师讲的"带来什么"）
 *   - 代运营 SOP 原写"变现→教知识/晒过程，人设→讲故事，流量→聊观点"
 *   - 选题板块只分"流量/变现"两种，人设型直接没了
 *   - 旧的定位兜底里还躺着知识库里没有的"起号期 流量60/人设30/变现10"
 * 模型拿到哪套就按哪套写，于是拿教知识去做流量、拿段子去做变现。
 *
 * 【依据】
 *   小黄：第17节 选题三大原则（覆盖人群、能否提供价值：有趣、有用、有共鸣、猎奇、长见识、引发情绪变化；比用户更深的认知）；
 *         精编版 9.1「三种目的」、9.2 三个判断标准、9.3 受众扩展、第10章 脚本结构库
 *   薛老师：2. 四大核心脚本；8-15 聊观点/晒过程/教知识/讲故事的结构；5. 定量+变量、人群垂直；八大爆款元素
 *   代运营从0到1创作SOP：05 单条视频生产（每条只选1个主目标、目的决定框架和结尾指令、变现→A/B 人设→C 流量→D）
 *   实体店通用选题SOP：三词根（人群×场景×行业）与四种脚本模式
 *   产品方 2026-10-25 定义：人货场 + 三有 + 爆款元素 + 看点噱头（见上）
 */

