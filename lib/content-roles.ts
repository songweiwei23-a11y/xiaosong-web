/** 完整说明：给定位、内容定位、起号、选题这类要做规划的板块 */
export function rolesGuide(): string {
  const block = (r: ContentRole) => {
    const s = ROLE_SPECS[r];
    return `#### ${r}：${s.job}
- **拍什么方向**：${s.directions}
- **用什么形式**：${s.scriptTypes}
- **结构例子**（按内容挑一个，骨架照着走）：
${s.structures.map((x) => `  - ${x}`).join('\n')}
- **怎么策划**：${s.planning}
- **36 计里常用在这种目的上的**（只是参考）：${TACTIC_ROLES[r].join('、')}
- **看什么数据**：${s.metrics}
- **结尾行动指令**：${s.cta}
- **最常见的错**：${s.pitfalls}`;
  };
  return `### 三种视频：流量型（大流量） / 人设型 / 变现型

${ROLE_RULES}

${CONTENT_ROLE_LIST.map(block).join('\n\n')}`;
}

/** 单条内容用的精简版：给脚本、标题、开篇、分镜、审稿 */
export function roleBrief(role: ContentRole, elementNames: string[] = VIRAL_ELEMENT_NAMES): string {
  const s = ROLE_SPECS[role];
  const std = role === '流量型' ? `\n- 大流量标准：${bigTrafficStandard(elementNames)}` : '';
  return `### 这条是${role}视频：${s.job}
- 方向：${s.directions}
- 形式：${s.scriptTypes}
- 结构例子（挑最合适的一个）：${s.structures.join('；')}
- 结尾行动指令：${s.cta}
- 别犯的错：${s.pitfalls}${std}`;
}

/**
 * 脚本类型 → 默认目的（只是默认，不是定义）。
 * 聊观点、讲故事默认归人设型；其余默认变现型。大流量要看内容本身，不看脚本，所以这里不做大流量的默认。
 */
export function defaultRoleOfScriptType(scriptType: string): ContentRole {
  if (/观点|话题|discuss/.test(scriptType)) return '人设型';
  if (/故事|story/.test(scriptType)) return '人设型';
  return '变现型';
}

/**
 * 单条内容板块（标题、开篇、分镜、审稿）不知道目的时，让模型先判断再按目的做。
 * 各板块关心的角度不同：标题开篇看"怎么抓人"，分镜看"镜头重点"，审稿看"前后是否一致"。
 */
export function roleInferRule(focus: 'hook' | 'shots' | 'review'): string {
  const line = (r: ContentRole) => {
    const s = ROLE_SPECS[r];
    if (focus === 'hook') return `- **${r}**（${s.job}）：${s.hook}`;
    if (focus === 'shots') return `- **${r}**：${s.shots}`;
    const names = s.structures.map((x) => x.split('：')[0]).join(' / ');
    return `- **${r}**：结构可参考 ${names}；结尾按目的只给一个动作（${s.cta}），没有就要指出；用户明确说不要结尾指令时不算问题；不能因不套骨架就判不合格`;
  };
  const head =
    focus === 'review'
      ? '先读取用户明确目的和带入的连续设置，再从稿子核对是否一致；未标目的才参考流量型（大流量）、人设型、变现型，混合目的保留，不强制归类：'
      : '已带入的用户目的、人群、主线优先，不从主题重新定目的；没有明确目的时才参考下列类型选择表达，混合目的完整保留：';
  return `### 🎯 先判断这条视频的目的

${head}
${CONTENT_ROLE_LIST.map(line).join('\n')}`;
}
