/**
 * 选题产出的四个标签（2026-10-19，分工方案第 2 步）。
 *
 * 每条选题要说清：属于内容定位里哪个系列、这条的目的（流量 / 人设 / 变现）、结尾只留哪一个动作、
 * 对应商业定位的哪一步成交。标签让产出能追溯到「为什么拍这条」，也让质检能查：
 * 有没有新造系列、有没有漏标目的和结尾。
 *
 * 脚本不加标签：脚本是要照着念的，标签混进去会污染「复制纯文案」。脚本只约束结尾动作和目的一致。
 */

export const TOPIC_TAGS = ['方向', '目的', '结尾动作', '成交步骤'] as const;

/** 选题的四个标签的提示词块，只给选题策划板块 */
export function topicTagBlock(): string {
  return [
    '## 🏷 每条选题的四个标签（缺一个就不算完成）',
    '',
    '- **【方向】**：写内容定位里的系列原名，或者用户自己定的方向（写【自定义】，再用一句话说清是什么）。方向是用户的选择：不硬凑进系列，也不替用户改成别的方向。',
    '- **【目的】**：流量、人设、变现三选一。三类的比例按行业建议来分配，不自己另定。',
    '- **【结尾动作】**：每条只留一个动作，且和目的匹配。变现型指向成交动作；人设型只做关注或看主页；流量型只做关注或评论。',
    '- **【成交步骤】**：变现型写商业定位里对应的那一步原名；非变现写「—」。',
    '- 写到价格、金额、人均、小票数字时，只用档案里有的；档案里没有就写【待确认】或「金额打码」，**不替它编数字**，哪怕系列或成交步骤里提到了小票和价格。',
    '',
    '每条选题都按这四行写在拍摄角度前面，格式统一。',
  ].join('\n');
}

const TAG_RE = (tag: string) => new RegExp(`【${tag}】|(^|\\n)\\s*(\\*\\*)?${tag}(\\*\\*)?\\s*[：:]`);

/**
 * 选题输出里缺标签的条目。按「## 选题N」分段，每段都要有四个标签。
 * 识别不出分段（格式不对）时返回空：无法判断，不误报。
 */
export function topicTagIssues(output: string): string[] {
  const blocks = output.split(/^\s*#{1,4}\s*选题\s*\d+[^\n]*$/m).slice(1);
  const issues: string[] = [];
  blocks.forEach((block, i) => {
    const missing = TOPIC_TAGS.filter((tag) => !TAG_RE(tag).test(block));
    if (missing.length) issues.push(`第 ${i + 1} 条选题缺少标签「${missing.join('、')}」`);
  });
  return issues;
}
