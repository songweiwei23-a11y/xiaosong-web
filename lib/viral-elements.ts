export interface ScriptFamily {
  /** 脚本类型名，必须与课程原文一字不差 */
  name: string;
  /** 这一类脚本主要解决哪个生意问题 */
  purpose: string;
  /** 课程里对它的定位，用来说明为什么要分这四类 */
  note: string;
}

