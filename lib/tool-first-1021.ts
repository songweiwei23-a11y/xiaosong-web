/**
 * 八大爆款元素的提示词（10-21 原文的写法：选中角度 → 按句式出选题 → 标注元素和句式）。
 * 元素的名字、原理、句式用现在的（名字 10-25 按产品方定的薛老师名单统一过）；只回到 10-21 的提示词文字。
 * 10-28、10-29 加的六条句式规则（不许照抄、负面句式不落自家货、句式不做证明等）不在这里。
 */
export function viralElementPrompt1021(ids: string[]): string {
  const picked = ids.map((id) => VIRAL_ELEMENTS.find((e) => e.id === id)).filter((e): e is ViralElement => !!e);
  if (picked.length === 0) return '';
  const lines = [
    '【八大爆款元素】选中以下角度，按给定句式出选题：',
    '',
    ...picked.flatMap((e) => [`▸ ${e.name}（${e.hook}）`, `  可套句式：${e.patterns.join(' / ')}`]),
    '',
    '要求：',
    '- 每条选题必须落在上面某一个句式上，把 X 换成本行业的具体东西',
    '- 句式是知识库给定的，不要自己另造一套',
    '- 每条选题后标注用的是哪个元素、套的哪个句式',
  ];
  return lines.join('\n');
}

/** 36 计清单（10-21 原文：按目的筛，标【最适合的目的】） */
export function tacticIndex1021(opts: { roles?: ContentRole[]; exclude?: string[] } = {}): string {
  const roles = opts.roles?.length ? opts.roles : CONTENT_ROLE_LIST;
  const exclude = new Set(opts.exclude ?? []);
  const lines = GROWTH_TACTICS.filter((t) => !exclude.has(t.name))
    .filter((t) => {
      const r = roleOfTactic(t.name);
      return r ? roles.includes(r) : true;
    })
    .map((t) => `- 第${t.no}计 **${t.name}**【${roleOfTactic(t.name) ?? '流量型'}】：${t.formula}（适合：${t.fit}）`);
  return `#### 起号 36 计清单（计名【最适合的目的】：结构公式）\n\n${lines.join('\n')}`;
}
