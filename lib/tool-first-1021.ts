/** 三种视频的完整说明（10-21 原文 + 三句） */
export function rolesGuide1021(): string {
  const block = (r: ContentRole) => {
    const s = ROLE_SPECS_1021[r];
    return `#### ${r}：${s.job}
- **拍什么方向**：${s.directions}
- **用什么脚本**：${s.scriptTypes}
- **脚本结构**（按内容挑一个，骨架照着走）：
${s.structures.map((x) => `  - ${x}`).join('\n')}
- **怎么策划**：${s.planning}
- **起号打法里适合它的**：${TACTIC_ROLES[r].join('、')}
- **看什么数据**：${s.metrics}
- **结尾行动指令**：${s.cta}
- **最常见的错**：${s.pitfalls}`;
  };
  return `### 三种视频：流量型 / 人设型 / 变现型

${ROLE_RULES_1021}

${CONTENT_ROLE_LIST.map(block).join('\n\n')}`;
}

