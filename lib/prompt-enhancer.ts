// ========== 阶段1：话术禁忌和示例参考增强模块 ==========

// 1. 构建带示例和禁忌的增强提示词
export function buildEnhancedPrompt(params: {
  basePrompt: string;
  scriptType: string;
  duration: string;
  structureType: string;
  hookType: string;
  isAd: boolean;
}): string {
  const { basePrompt, scriptType, duration, structureType, hookType, isAd } = params;
  
  // 获取相关示例
  const exampleScript = getExampleByType(scriptType, duration, structureType);
  
  // 构建强制要求
  const mandatoryRequirements = `
## 🚨 强制质量标准（不满足将被判定为不合格）

### ✅ 必须包含的7大元素：

1. **开场钩子**（0-X秒）
   - ❌ 禁止："大家好我是XX""今天我要分享""欢迎来到我的频道"
   - ✅ 必须：用数字对比、价格冲击、反常识观点、悬念好奇直接开场
   - 示例："我见过最快的3天涨粉2000，也见过最慢的3个月还是0"

2. **情绪波点标注**（至少2处）
   - 用emoji明确标注：😰焦虑 😓认同 💕共鸣 🤝痛点 ⚡高潮
   - 示例：**【镜头2】3-8秒 😰焦虑+共鸣波点**

3. **秒数时间轴**（至少3处）
   - 每个段落必须标注时间：0-8秒、8-20秒、20-35秒等
   - 确保时间连贯，不要跳跃

4. **镜头画面描述**（每个场景）
   - 必须包含：机位/景别、台词、情绪、画面、动作
   - 示例：**【镜头1】** - 台词："..." - 情绪：语速快、重读 - 画面：手势配合

5. **金句**（8-20字）
   - 用""引起来，可转发、可记忆
   - 示例："抖音不是拍给自己看的，是拍给用户要的"（15字）

6. **接地气口语表达**（至少2处）
   - ✅ 推荐："你妈给的点赞""手指头都划走了""说人话就是""你猜怎么着""关注你干啥"
   - ❌ 禁止："非常好""特别棒""我觉得"等空洞表达

7. **CTA行动指令**
   - 明确告诉用户下一步做什么
   - 示例："评论区扣1""点赞收藏""到店报我名字""团购链接左下角"

---

### ❌ 绝对禁止的话术（出现即判定为0分）：

**开场废话**：
- "大家好我是XX"
- "今天我要分享"
- "今天给大家带来"
- "欢迎来到我的频道"
- "感谢大家观看"

**书面语表达**（扣5分/处）：
- "综上所述"
- "通过以上分析"
- "根据调查显示"
- "由此可见"
- "总而言之"

**空洞表达**（扣2分/处）：
- "非常好""特别棒"（必须具体化：好在哪里？）
- "我觉得""可能""应该""大概"（必须用确定语气）

---

### 📋 MCN级示例参考（9.5分）

${exampleScript}

---

### 🎯 生成策略

1. **严格对标示例**：参考以上9.5分示例的格式、节奏、表达方式
2. **必须避开禁忌**：不要出现任何废话开场和书面语
3. **强制包含元素**：7大必备元素缺一不可
4. **接地气表达**：多用"你妈""手指头""干嘛"等口语，少用"非常""特别"
5. **情绪饱满**：至少2处明确的情绪高潮点

---
`;

  // 组合最终prompt
  return mandatoryRequirements + '\n' + basePrompt;
}

// 2. 根据类型获取示例脚本
function getExampleByType(scriptType: string, duration: string, structureType: string): string {
  const durationNum = parseInt(duration) || 60;
  
  // 广告类型
  if (scriptType.includes('ad_')) {
    return getAdExample();
  }
  
  // 内容类型
  if (durationNum <= 30) {
    return get30sExample();
  } else if (scriptType === 'teach' || structureType === 'compare') {
    return get60sTeachExample();
  } else if (scriptType === 'show' || scriptType === 'story') {
    return get60sStoryExample();
  }
  
  // 默认返回教知识示例
  return get60sTeachExample();
}

