/**
 * 所有写稿板块共用的两条底线（2026-10-05 质量整改，docs/开物质量深度研究_20261005/问题成因与优化实施方案.md）。
 *
 * 1. 优先级：事实与安全边界 > 用户的明确要求 > 这条内容的创作目的 > 模板和标准。
 *    用户的明确要求不按字数决定地位（原来脚本页不到 100 字就排在 MCN 标准后面）。
 * 2. 不编造：缺数据时用不带数字的写法；虚构的示例必须标【示例】，不能写成真实顾客说的话；
 *    不替老板承诺没说过的福利；不许自称「自检通过、无编造」（程序会核对，见 lib/quality-checks）。
 *
 * 从 buildContextBlock（lib/creator-context）统一带进各板块，自由对话在服务端另带一句（app/api/dify/chat）。
 */
import type { Board } from './context-manifest';

export const PRIORITY_ORDER = '事实与安全边界（人设事实卡、禁忌、平台规则） > 用户这次的明确要求 > 这条内容的创作目的 > 模板和标准';

/** 这些板块产出要对外发的文案，带上底线规则 */
export const OUTPUT_RULE_BOARDS = new Set<Board>(['topic', 'script', 'storyboard', 'review', 'title', 'growth', 'remix', 'freeChat', 'direction']);

export const FACT_RULES = [
  '价格、百分比、销量、年限、分店数、获奖、顾客经历——资料里没有的一律不写；需要具体感时，用不带数字的说法（「90% 的人」不行，「不少人」可以；「人均 68 元」不行，「价格很亲民」可以）。',
  '可以写虚构的示例帮助理解，但必须标【示例】，不能写成「有位顾客说……」这种真实见证。',
  '送什么、包什么、保证什么、打几折——老板没说过的经营承诺不能替他答应。',
  '真想写一个具体数字又没有资料，用【待确认：xx】占位，让用户自己填。',
  '不要写「自检通过」「无编造」「数据真实」这类自我认证，系统会单独核对。',
];

export function outputRulesBlock(): string {
  return ['## 🧭 写作底线（每条都要遵守）', '', `- **优先级**：${PRIORITY_ORDER}。用户的明确要求哪怕只有一句（「只换开头」「别提价格」），也排在模板前面。`, ...FACT_RULES.map((r) => `- ${r}`)].join('\n');
}

/** 自由对话每一轮都带的一句（服务端加，不依赖这一轮有没有带账号背景） */
export const FREE_CHAT_FACT_LINE = '不编造：资料里没有的价格、百分比、顾客经历、经营承诺不要写成事实，需要时标【示例】或【待确认】；不要自称「自检通过、无编造」。用户这次说的明确要求优先于任何模板。';
