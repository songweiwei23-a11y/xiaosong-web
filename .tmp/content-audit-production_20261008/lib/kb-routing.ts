/**
 * 编导知识库按任务分流（2026-10-05 质量整改第二阶段）。
 *
 * 实测（同一个脚本任务，正式「开物」）：
 *   查知识库：输入 32,363 token，出第一个字 9～15.7 秒（5 组检索里最慢一组单独 10 秒）
 *   不查：    输入  8,333 token，出第一个字 3.5 秒
 * 检索开关就是交给 Dify 的 search_query：空的就不检索（0 条、十几毫秒），不用改工作流。
 *
 * 规则：写脚本、选题、审稿、标题这些板块照常查（它们靠编导方法）；
 * 画布里改一句、按资料修正、深度研究、偏好学习不查；自由对话只在问的是短视频相关的事时才查——
 * 「Excel 怎么按月汇总」「帮我写个请假条」用不上编导知识，查了只会更慢、更贵、还可能被无关资料带偏。
 */

/** 问的是不是短视频、内容创作、账号运营相关的事 */
const KB_TOPIC = /短视频|视频|抖音|快手|小红书|视频号|直播|带货|脚本|选题|口播|拍摄|拍法|拍一条|镜头|分镜|标题|封面|开头|开篇|钩子|账号|起号|涨粉|粉丝|流量|完播|播放|爆款|文案|定位|人设|剪辑|运营|编导|达人|种草|探店|评论区|私域|团购|引流|获客|成交|转化|话术|台词|素材|知识库/;

export function freeChatNeedsKnowledge(question: string): boolean {
  return KB_TOPIC.test(question || '');
}

/** 这些任务从不查编导知识库 */
export const NO_KB_TASKS = new Set(['画布改写']);

