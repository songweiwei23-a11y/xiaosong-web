/** 分组顺序，界面按这个顺序渲染 */
export const CONTENT_TYPE_GROUPS: ContentTypeGroup[] = ['口播类', '展示类', '场景类', '叙事类'];

const BY_VALUE = new Map(CONTENT_TYPES.map((t) => [t.value, t]));

export function getContentType(value: string | undefined): ContentTypeDef | undefined {
  return value ? BY_VALUE.get(value) : undefined;
}

/** 注入分镜提示词的本类要点；类型不认识时返回空串，调用方照常工作 */
export function contentTypeGuide(value: string | undefined): string {
  return getContentType(value)?.guide ?? '';
}

export function contentTypeExample(value: string | undefined): string {
  return getContentType(value)?.example ?? CONTENT_TYPES[0].example;
}

/** 所有合法取值，给 AI 推荐的提示词用——手写那份列表曾经和实际选项对不上 */
