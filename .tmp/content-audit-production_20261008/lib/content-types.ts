/**
 * 内容类型：界面选项 + 示例脚本 + 分镜设计要点，三样放在一起。
 *
 * 【为什么合并】改造前这三样散在两个文件里：storyboard/page.tsx 存界面卡片和
 * 示例脚本，storyboard-standards.ts 存 CONTENT_TYPE_GUIDE，中间没有任何关联。
 * 后果是加一个类型很容易只加了卡片、忘了写方法论——而缺方法论不会报错，
 * 提示词里那一整段「本类内容的特殊要求」就是静默消失，产出质量降一档也没人知道。
 * 现在放在一起，再配一条测试卡住：每个类型必须三样俱全。
 *
 * 【内容依据】类型划分和各自的拍法要点取自我们自己的知识库，不是凭空分的：
 *   · 四大脚本类型：教知识型 / 晒过程型 / 聊观点型 / 讲故事型
 *   · 实体店四大内容方向：过程展示 / 测评产品 / 任务挑战 / 事件体验
 *   · 口播四视角、vlog 四种呈现、探店的火车节模型、景别隔级切换等
 * 原来只有 6 个类型（美食/VLOG/教程/产品/故事/访谈），恰恰漏掉了实体店老板
 * 最常拍的几类：口播、探店、晒过程、测评对比、挑战体验、客户案例。
 *
 * 【分组依据】按**怎么拍**分，不是按脚本结构分——分镜关心的是景别、运镜、
 * 有没有操作过程、人是否移动、有没有对手戏。所以「解题型/揭秘型」这类
 * 脚本结构上的区分不单独立项，它们在分镜上都是「口播 + B-roll」。
 *
 * 【旧值保留】food/vlog/tutorial/product/story/interview 这六个 value 原样保留，
 * 历史记录里存的就是它们，改了会让老数据对不上类型。
 */

