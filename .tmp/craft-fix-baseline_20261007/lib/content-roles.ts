export function roleOfTactic(name: string): ContentRole | null {
  for (const r of CONTENT_ROLE_LIST) if (TACTIC_ROLES[r].includes(name)) return r;
  return null;
}

/** 通用规则：适用于每一条视频 */
export const ROLE_RULES = `**三条铁律**（代运营 SOP 原话）：
- **每条视频只选一个主目的**——流量、人设、变现三个都要，等于三个都失败
- **目的决定一切**：选题方向、脚本结构、结尾行动指令都跟着目的走，这一步不能跳
- **结尾行动指令只要一个**：关注、评论、私信、到店，选一个说清楚，不能全要

**脚本类型不等于目的**：同一种脚本可以服务不同目的——泛知识（大众入口）是流量型，
专业知识（精准人群的难题）是变现型；讲自己的成长是人设型，讲帮客户做成的事是变现型。
判断看"这条视频要观众做什么"，不看用了哪种脚本。

**系列也一样**：一个系列只担一个主目的，系列里每一集的目的和系列一致。`;

/** 完整说明：给定位、内容定位、起号、选题这类要做规划的板块 */
export function rolesGuide(): string {
  const block = (r: ContentRole) => {
    const s = ROLE_SPECS[r];
    return `#### ${r}：${s.job}
- **拍什么方向**：${s.directions}
- **用什么脚本**：${s.scriptTypes}
- **脚本结构**（按内容挑一个，骨架照着走）：
${s.structures.map((x) => `  - ${x}`).join('\n')}
- **怎么策划**：${s.planning}
- **起号打法里适合它的**：${TACTIC_ROLES[r].join('、')}
- **看什么数据**：${s.metrics}
- **结尾行动指令**：${s.cta}
- **最常见的错**：${s.pitfalls}`;
  };
  return `### 三种视频：流量型 / 人设型 / 变现型

${ROLE_RULES}

${CONTENT_ROLE_LIST.map(block).join('\n\n')}`;
}

/** 单条内容用的精简版：给脚本、标题、开篇、分镜、审稿 */
export function roleBrief(role: ContentRole): string {
  const s = ROLE_SPECS[role];
  return `### 这条是${role}视频：${s.job}
- 方向：${s.directions}
- 脚本结构（挑最合适的一个）：${s.structures.join('；')}
- 结尾行动指令：${s.cta}
- 别犯的错：${s.pitfalls}`;
}

/**
 * 脚本类型 → 默认目的（SOP：变现→教知识/晒过程，人设→讲故事，流量→聊观点）。
 * 只是默认——泛知识的教知识是流量型、成功案例的讲故事是变现型，用户可以改。
 */
export function defaultRoleOfScriptType(scriptType: string): ContentRole {
  if (/观点|话题|discuss/.test(scriptType)) return '流量型';
  if (/故事|story/.test(scriptType)) return '人设型';
  return '变现型';
}

/**
 * 单条内容板块（标题、开篇、分镜、审稿）不知道目的时，让模型先判断再按目的做。
 * 各板块关心的角度不同：标题开篇看"怎么抓人"，分镜看"镜头重点"，审稿看"前后是否一致"。
 */
export function roleInferRule(focus: 'hook' | 'shots' | 'review'): string {
  const line = (r: ContentRole) => {
    const s = ROLE_SPECS[r];
    if (focus === 'hook') return `- **${r}**（${s.job}）：${s.hook}`;
    if (focus === 'shots') return `- **${r}**：${s.shots}`;
    const names = s.structures.map((x) => x.split('：')[0]).join(' / ');
    return `- **${r}**：结构该是 ${names} 这类；结尾只要${s.cta}；常见的错是${s.pitfalls}`;
  };
  const head =
    focus === 'review'
      ? '先从稿子本身判断它是**流量型**、**人设型**还是**变现型**，再查目的、结构、结尾指令三者是否一致：'
      : '先从主题判断这条是**流量型**、**人设型**还是**变现型**（一条只担一个目的），再按对应的要求来：';
  return `### 🎯 先判断这条视频的目的

${head}
${CONTENT_ROLE_LIST.map(line).join('\n')}`;
}
